"""Three-object regression fixture. Run in disposable factory-startup Blender."""
import sys
import tempfile
from pathlib import Path

import bpy
from mathutils import Vector

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from pipeline.bake import bake_atlas, duplicate_and_join
from pipeline.common import mesh_objects
from pipeline.check import check, assembly_preservation, mesh_health

bpy.ops.wm.read_factory_settings(use_empty=True)
root = bpy.data.objects.new('FixtureRoot', None)
bpy.context.scene.collection.objects.link(root)
sources = []
for index in range(3):
    bpy.ops.mesh.primitive_cube_add(location=(index * 3, 0, 0))
    obj = bpy.context.object
    obj.name = f'Fixture_{index}'
    obj.parent = root
    obj.data.uv_layers[0].name = 'StickerDecal'
    material = bpy.data.materials.new(f'FixtureMaterial_{index}')
    material.use_nodes = True
    coords = material.node_tree.nodes.new('ShaderNodeTexCoord')
    noise = material.node_tree.nodes.new('ShaderNodeTexNoise')
    material.node_tree.links.new(coords.outputs['Object'], noise.inputs['Vector'])
    shader = next(n for n in material.node_tree.nodes if n.type == 'BSDF_PRINCIPLED')
    material.node_tree.links.new(noise.outputs['Color'], shader.inputs['Base Color'])
    obj.data.materials.append(material)
    sources.append(obj)
sources[0].modifiers.new('BevelFixture', 'BEVEL').width = .2
sources[2].hide_render = True
bpy.context.view_layer.update()
selected = mesh_objects([root, sources[0]])
assert selected == sources[:2], [o.name for o in selected]
depsgraph = bpy.context.evaluated_depsgraph_get()
expected = sorted(tuple(round(c, 6) for c in obj.matrix_world @ vertex.co)
                  for obj in selected
                  for vertex in obj.evaluated_get(depsgraph).data.vertices)
source_state = [(o.data, o.matrix_world.copy(), list(o.data.materials)) for o in selected]
atlas, _, _ = duplicate_and_join(selected)
actual = sorted(tuple(round(c, 6) for c in atlas.matrix_world @ vertex.co)
                for vertex in atlas.data.vertices)
assert expected == actual, 'Evaluated geometry changed on join'
assert atlas.data.uv_layers.get('StickerDecal') is not None
assert len(atlas.modifiers) == 0
for obj, (mesh, matrix, materials) in zip(selected, source_state):
    assert obj.data == mesh and obj.matrix_world == matrix
    assert list(obj.data.materials) == materials
    assert all(m not in [s.material for s in atlas.material_slots] for m in materials)
for slot in atlas.material_slots:
    node = next(n for n in slot.material.node_tree.nodes if n.type == 'TEX_COORD')
    assert node.object in selected
print('ATLAS_PREPARATION_PASS: evaluated vertices, source preservation, hidden exclusion, deduplication, UV names')

# Independent numeric check: colour baked at a face's AtlasUV centroid must
# match that face's known constant source, not a source UV or another object.
palette = [(0.8, 0.1, 0.05, 1), (0.05, 0.6, 0.15, 1)]
for obj, colour in zip(selected, palette):
    tree = obj.data.materials[0].node_tree
    shader = next(n for n in tree.nodes if n.type == 'BSDF_PRINCIPLED')
    for link in list(shader.inputs['Base Color'].links):
        tree.links.remove(link)
    shader.inputs['Base Color'].default_value = colour
    shader.inputs['Alpha'].default_value = 1.0 if obj == selected[0] else .32
with tempfile.TemporaryDirectory(prefix='atlas-fixture-') as directory:
    baked, report = bake_atlas(selected, directory, resolution=128, margin=2, samples=1)
    image = bpy.data.images.get('Atlas_basecolor')
    pixels = list(image.pixels)
    layer = baked.data.uv_layers['AtlasUV']
    errors = []
    alpha_errors = []
    for face in baked.data.polygons:
        world = baked.matrix_world @ face.center
        target = palette[0 if world.x < 1.5 else 1][:3]
        uv = sum((layer.data[i].uv for i in face.loop_indices), Vector((0, 0))) / len(face.loop_indices)
        x, y = min(127, int(uv.x * 128)), min(127, int(uv.y * 128))
        sample = pixels[(y * 128 + x)*4:(y * 128 + x)*4+3]
        # Generated byte-buffer sRGB images expose encoded samples here. Decode
        # with the standard transfer function before comparing Principled values.
        linear = [c / 12.92 if c <= .04045 else ((c + .055) / 1.055)**2.4 for c in sample]
        errors.append(max(abs(a-b) for a, b in zip(linear, target)))
        expected_alpha = 1.0 if world.x < 1.5 else .32
        alpha_errors.append(abs(pixels[(y * 128 + x)*4+3] - expected_alpha))
    assert max(errors) < .03, ('Atlas/source pixel mismatch', max(errors))
    print('ATLAS_CENTROID_PASS', len(errors), 'faces, max linear RGB error', max(errors))
    assert max(alpha_errors) < 1/255 + 1e-6, ('Alpha transfer mismatch', max(alpha_errors))
    print('ATLAS_ALPHA_PASS', max(alpha_errors))
    assert len(report['parts']) == len(selected)
    for source, name in zip(selected, report['parts']):
        part = bpy.data.objects[name]
        before = sorted(tuple(round(c, 5) for c in source.matrix_world @ v.co)
                        for v in source.evaluated_get(bpy.context.evaluated_depsgraph_get()).data.vertices)
        after = sorted(tuple(round(c, 5) for c in part.matrix_world @ v.co) for v in part.data.vertices)
        assert before == after, ('Split changed geometry', source.name)
        evaluated = source.evaluated_get(bpy.context.evaluated_depsgraph_get()).data
        evaluated.calc_loop_triangles()
        assert len(part.data.polygons) == len(evaluated.loop_triangles), 'Part kept foreign faces'
        assert len({face.material_index for face in part.data.polygons}) <= len(part.data.materials)
        used = {face.material_index for face in part.data.polygons}
        for index in used:
            shader = next(n for n in part.data.materials[index].node_tree.nodes if n.type == 'BSDF_PRINCIPLED')
            assert shader.inputs['Alpha'].is_linked == (source == selected[1])
    assert len(report['assembly_roots']) == 1
    parent = bpy.data.objects[report['assembly_roots'][0]]
    first = bpy.data.objects[report['parts'][0]]
    old_world = first.matrix_world.copy()
    parent.location.x += 2
    bpy.context.view_layer.update()
    assert abs(first.matrix_world.translation.x - old_world.translation.x - 2) < 1e-5
    assert selected[0].matrix_world == source_state[0][1]
    print('ATLAS_ASSEMBLY_PASS: local geometry, alpha classes, independent parent motion')
    import json
    manifest = Path(directory) / 'assembly.json'
    manifest.write_text(json.dumps({'groups': [report]}))
    assert not assembly_preservation(manifest, [1])['ok'], 'Translated assembly was not rejected'
    parent.location.x -= 2
    bpy.context.view_layer.update()
    assert assembly_preservation(manifest, [1])['ok'], 'Restored assembly should pass'
    checks = check({'objects': [selected[0].name], 'out_dir': directory,
                    'uv_layer': 'StickerDecal', 'padding': True, 'coplanar': True,
                    'profile': 'prop'})
    assert checks['ok'], checks['health']
    assert checks['padding'] and checks['coplanar']
    print('PIPELINE_CHECK_ADAPTERS_PASS: original padding and coplanar helpers')

bpy.ops.mesh.primitive_cube_add()
tiny = bpy.context.object
for vertex in tiny.data.vertices:
    vertex.co *= 1e-5
assert mesh_health([tiny])['ok'], 'Small nonzero faces must not be called zero area'
bad_mesh = bpy.data.meshes.new('DeliberatelyDegenerate')
bad_mesh.from_pydata([(0, 0, 0), (1, 0, 0), (2, 0, 0)], [], [(0, 1, 2)])
bad = bpy.data.objects.new('DeliberatelyDegenerate', bad_mesh)
bpy.context.scene.collection.objects.link(bad)
assert not mesh_health([bad])['ok'], 'Genuinely zero-area face should fail'
print('DIAGNOSTIC_CONTROLS_PASS: tiny valid faces, zero-area failure, translated assembly failure')
